import { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import { useNavigate, useParams } from 'react-router-dom'
import {
  ArrowLeft,
  BookOpen,
  Download,
  Eye,
  Loader2,
  Pencil,
  Redo2,
  ShieldCheck,
  Undo2,
  Upload
} from 'lucide-react'
import { toast } from 'sonner'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import { Dialog } from '@/components/ui/dialog'
import { SaveIndicator } from '@/components/save-indicator'
import { Input } from '@/components/ui/input'
import {
  addComponent,
  addTab,
  applyLayouts,
  createComponent,
  createSheetContext,
  createPreviewValues,
  duplicateComponentInSchema,
  exportTemplateJson,
  findComponentById,
  findKeyUsages,
  isAutoGeneratedKey,
  keyFromLabel,
  moveComponentToTab,
  moveTab,
  nextFreeRow,
  removeComponent,
  removeTab,
  renameKeyInSchema,
  renameTab,
  takenKeysOf,
  updateComponent,
  validateSchema,
  type ComponentType,
  type GridPosition,
  type SheetComponent,
  type SheetSchema
} from '@/lib/sheet'
import { templateRepository } from '@/features/sheet-templates/repository'
import { FormulaGuide } from '@/features/formula-guide/formula-guide'
import { errorMessage } from '@/lib/db/errors'
import { useBuilderStore } from './builder-store'
import { GridCanvas } from './grid-canvas'
import { Palette } from './palette'
import { PreviewPanel } from './preview-panel'
import { PropertiesPanel } from './properties-panel'
import { TabsBar } from './tabs-bar'
import { ValidationPanel } from './validation-panel'

/** Construtor de fichas (seção 5.2). */
export function SheetBuilderPage(): React.JSX.Element {
  const { templateId } = useParams<{ templateId: string }>()
  const navigate = useNavigate()

  const store = useBuilderStore()
  const {
    schema: loadedSchema,
    name,
    template,
    activeTabId,
    selectedId,
    saveState,
    previewing,
    past,
    future
  } = store

  const [draggingType, setDraggingType] = useState<ComponentType | null>(null)
  const [showValidation, setShowValidation] = useState(false)
  const [deleteTarget, setDeleteTarget] = useState<SheetComponent | null>(null)
  const [publishing, setPublishing] = useState(false)
  const [showGuide, setShowGuide] = useState(false)
  const [loadError, setLoadError] = useState<string | null>(null)
  // Esquema de antes do arrasto, para o Desfazer receber um passo só por interação.
  const interactionStart = useRef<SheetSchema | null>(null)

  // Carrega o modelo e liga o store ao repositório.
  useEffect(() => {
    store.attach(templateRepository)

    let active = true
    if (templateId === undefined) return

    void templateRepository.get(templateId).then(
      (found) => {
        if (!active) return
        if (found === null) {
          setLoadError('Este modelo não existe mais.')
          return
        }
        store.load(found)
      },
      (error: unknown) => {
        if (active) setLoadError(`Não consegui abrir o modelo. ${errorMessage(error)}`)
      }
    )

    return () => {
      active = false
      // Grava o que estava esperando o salvamento automático antes de limpar a tela; o
      // retrato do rascunho é tirado agora, então o `reset` logo abaixo não o atrapalha.
      void useBuilderStore.getState().flush()
      store.reset()
    }
    // Só recarrega quando muda de modelo.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [templateId])

  const commit = useCallback((next: SheetSchema) => {
    useBuilderStore.getState().commit(next)
  }, [])

  // Desfazer/Refazer por teclado (5.2).
  useEffect(() => {
    const onKeyDown = (event: KeyboardEvent): void => {
      if (!event.ctrlKey && !event.metaKey) return
      const key = event.key.toLowerCase()
      if (key === 'z' && !event.shiftKey) {
        event.preventDefault()
        useBuilderStore.getState().undo()
      }
      if (key === 'y' || (key === 'z' && event.shiftKey)) {
        event.preventDefault()
        useBuilderStore.getState().redo()
      }
    }

    window.addEventListener('keydown', onKeyDown)
    return () => window.removeEventListener('keydown', onKeyDown)
  }, [])

  const selected = useMemo(
    () =>
      loadedSchema === null || selectedId === null
        ? null
        : (findComponentById(loadedSchema, selectedId) ?? null),
    [loadedSchema, selectedId]
  )

  // Contexto com valores de teste: é o que faz o campo calculado mostrar um número na
  // grade do construtor em vez de ficar vazio.
  const canvasPreview = useMemo(() => {
    if (loadedSchema === null) return null
    const values = createPreviewValues(loadedSchema)
    return { values, context: createSheetContext(loadedSchema, values).context }
  }, [loadedSchema])

  const report = useMemo(
    () => (loadedSchema === null ? null : validateSchema(loadedSchema)),
    [loadedSchema]
  )

  if (loadError !== null) {
    return (
      <div className="flex h-full flex-col items-center justify-center gap-4">
        <p className="text-muted-foreground">{loadError}</p>
        <Button variant="outline" onClick={() => void navigate('/templates')}>
          Voltar para os modelos
        </Button>
      </div>
    )
  }

  if (loadedSchema === null || canvasPreview === null || report === null) {
    return (
      <div className="text-muted-foreground flex h-full items-center justify-center gap-2 text-sm">
        <Loader2 className="size-4 animate-spin" />
        Carregando modelo…
      </div>
    )
  }

  // Daqui para baixo o esquema existe. A cópia num const dá ao TypeScript a certeza de que
  // ele não é nulo também dentro das funções abaixo.
  const schema = loadedSchema

  function addFromPalette(type: ComponentType, position?: { x: number; y: number }): void {
    if (activeTabId === null) return
    const tab = schema.tabs.find((item) => item.id === activeTabId)
    if (tab === undefined) return

    const component = createComponent(type, {
      takenKeys: takenKeysOf(schema),
      position: position ?? { x: 0, y: nextFreeRow(tab) }
    })

    commit(addComponent(schema, activeTabId, component))
    store.select(component.id)
  }

  function changeSelected(change: Partial<SheetComponent>): void {
    if (selected === null) return

    let next = updateComponent(
      schema,
      selected.id,
      (component) => ({ ...component, ...change }) as SheetComponent
    )

    /*
      A chave é gerada do rótulo (5.2): enquanto o mestre não a editar à mão, ela acompanha
      o que ele escreve — criar um "Atributo" e chamá-lo de "Força" deixa a chave `forca`,
      sem precisar mexer em dois campos.
    */
    const newLabel = change.label
    if (newLabel !== undefined && isAutoGeneratedKey(selected.key, selected.label)) {
      const taken = takenKeysOf(schema).filter((key) => key !== selected.key)
      const candidate = keyFromLabel(newLabel, taken)
      if (candidate !== selected.key) next = renameKeyInSchema(next, selected.id, candidate)
    }

    commit(next)
  }

  function renameSelectedKey(newKey: string): void {
    if (selected === null) return
    commit(renameKeyInSchema(schema, selected.id, newKey))
    toast.success('Chave renomeada', {
      description: 'As fórmulas que usavam a chave antiga foram atualizadas.'
    })
  }

  function duplicateSelected(): void {
    if (selected === null) return
    const result = duplicateComponentInSchema(schema, selected.id)
    commit(result.schema)
    if (result.componentId !== null) store.select(result.componentId)
  }

  function confirmDelete(): void {
    if (deleteTarget === null) return
    commit(removeComponent(schema, deleteTarget.id))
    store.select(null)
    setDeleteTarget(null)
  }

  async function handleExport(): Promise<void> {
    if (template === null) return
    const text = exportTemplateJson({ ...template, name, draftSchema: schema })
    const result = await window.api.saveTextFile({
      suggestedName: `${name || 'modelo'}.json`,
      text,
      filters: [{ name: 'Modelo de ficha', extensions: ['json'] }]
    })

    if (result.status === 'saved') toast.success('Modelo exportado')
    if (result.status === 'error')
      toast.error('Não consegui exportar', { description: result.message })
  }

  async function handlePublish(): Promise<void> {
    if (templateId === undefined) return

    const validation = validateSchema(schema)
    if (!validation.ok) {
      setShowValidation(true)
      toast.error('Corrija os erros antes de publicar', {
        description: `${validation.errors.length} problema(s) impedem a publicação.`
      })
      return
    }

    setPublishing(true)
    try {
      await useBuilderStore.getState().saveNow()
      const version = await templateRepository.publish(templateId)
      const updated = await templateRepository.get(templateId)
      if (updated !== null) store.markPublished(updated)
      toast.success(`Versão ${version} publicada`, {
        description: 'Os jogadores passam a usar esta versão.'
      })
    } catch (error) {
      console.error(error)
      toast.error('Não consegui publicar o modelo', { description: errorMessage(error) })
    } finally {
      setPublishing(false)
    }
  }

  const publishedVersion = template?.versions.at(-1)?.version ?? null
  const usages = deleteTarget === null ? [] : findKeyUsages(schema, deleteTarget.key)

  return (
    <div className="flex h-full min-h-0 flex-col">
      <header className="flex flex-wrap items-center gap-2 border-b px-3 py-2">
        <Button
          variant="ghost"
          size="icon"
          onClick={() => void navigate('/templates')}
          aria-label="Voltar"
        >
          <ArrowLeft className="size-4" />
        </Button>

        <Input
          className="max-w-xs"
          value={name}
          onChange={(event) => store.setName(event.target.value)}
          aria-label="Nome do modelo"
        />

        <SaveIndicator state={saveState} />

        {publishedVersion !== null && (
          <Badge variant="secondary">publicado: v{publishedVersion}</Badge>
        )}

        <div className="ml-auto flex items-center gap-1">
          <Button
            variant="ghost"
            size="icon"
            disabled={past.length === 0}
            onClick={() => store.undo()}
            aria-label="Desfazer"
            title="Desfazer (Ctrl+Z)"
          >
            <Undo2 className="size-4" />
          </Button>
          <Button
            variant="ghost"
            size="icon"
            disabled={future.length === 0}
            onClick={() => store.redo()}
            aria-label="Refazer"
            title="Refazer (Ctrl+Y)"
          >
            <Redo2 className="size-4" />
          </Button>

          <Button
            variant="ghost"
            size="sm"
            onClick={() => setShowGuide(true)}
            title="Como escrever fórmulas e ligar um campo ao outro"
          >
            <BookOpen className="size-4" />
            Guia
          </Button>

          <Button
            variant={previewing ? 'default' : 'outline'}
            size="sm"
            onClick={() => store.setPreviewing(!previewing)}
          >
            {previewing ? <Pencil className="size-4" /> : <Eye className="size-4" />}
            {previewing ? 'Editar' : 'Ver como jogador'}
          </Button>

          <Button variant="outline" size="sm" onClick={() => setShowValidation(true)}>
            <ShieldCheck className="size-4" />
            Validar
            {report.errors.length > 0 && (
              <Badge variant="destructive" className="ml-1">
                {report.errors.length}
              </Badge>
            )}
          </Button>

          <Button variant="outline" size="sm" onClick={() => void handleExport()}>
            <Download className="size-4" />
            Exportar
          </Button>

          <Button size="sm" disabled={publishing} onClick={() => void handlePublish()}>
            <Upload className="size-4" />
            Publicar
          </Button>
        </div>
      </header>

      {previewing ? (
        <PreviewPanel schema={schema} activeTabId={activeTabId} onSelectTab={store.setActiveTab} />
      ) : (
        <div className="grid min-h-0 flex-1 grid-cols-[13rem_1fr_19rem] divide-x">
          <aside className="min-h-0 overflow-hidden">
            <Palette
              onAdd={(type) => addFromPalette(type)}
              onDragStart={setDraggingType}
              onDragEnd={() => setDraggingType(null)}
            />
          </aside>

          <section className="flex min-h-0 flex-col">
            <TabsBar
              schema={schema}
              activeTabId={activeTabId}
              onSelect={store.setActiveTab}
              onAdd={() => {
                const result = addTab(schema, `Aba ${schema.tabs.length + 1}`)
                commit(result.schema)
                store.setActiveTab(result.tab.id)
              }}
              onRename={(tabId, label) => commit(renameTab(schema, tabId, label))}
              onRemove={(tabId) => {
                commit(removeTab(schema, tabId))
                const remaining = schema.tabs.find((tab) => tab.id !== tabId)
                if (remaining !== undefined) store.setActiveTab(remaining.id)
              }}
              onMove={(tabId, direction) => commit(moveTab(schema, tabId, direction))}
            />

            <div className="min-h-0 flex-1 overflow-auto">
              {activeTabId !== null && (
                <GridCanvas
                  schema={schema}
                  tabId={activeTabId}
                  values={canvasPreview.values}
                  context={canvasPreview.context}
                  selectedId={selectedId}
                  draggingType={draggingType}
                  onSelect={store.select}
                  onLayoutsChange={(layouts: (GridPosition & { id: string })[]) => {
                    const next = applyLayouts(schema, activeTabId, layouts)
                    if (JSON.stringify(next) === JSON.stringify(schema)) return
                    /*
                      A grade avisa a cada passo do arrasto. Aqui só trocamos o esquema
                      (sem passo de histórico); o Desfazer recebe um passo único quando o
                      arrasto termina, senão um arrasto viraria dezenas de Ctrl+Z.
                    */
                    store.replace(next)
                  }}
                  onInteractionStart={() => {
                    interactionStart.current = schema
                  }}
                  onInteractionEnd={() => {
                    const before = interactionStart.current
                    interactionStart.current = null
                    if (before !== null) store.pushHistory(before)
                  }}
                  onDropNew={(position) => {
                    if (draggingType !== null) addFromPalette(draggingType, position)
                    setDraggingType(null)
                  }}
                />
              )}
            </div>
          </section>

          <aside className="min-h-0 overflow-auto">
            <PropertiesPanel
              // Só a troca de seleção recomeça o painel. Mudança de chave remonta apenas o
              // campo Chave lá dentro; se remontasse tudo, o Rótulo perderia o foco a cada
              // letra, porque a chave acompanha o rótulo enquanto digita.
              key={selected?.id ?? 'none'}
              schema={schema}
              component={selected}
              onChange={changeSelected}
              onRenameKey={renameSelectedKey}
              onDuplicate={duplicateSelected}
              onDelete={() => setDeleteTarget(selected)}
              onMoveToTab={(tabId) => {
                if (selected === null) return
                commit(moveComponentToTab(schema, selected.id, tabId))
                store.setActiveTab(tabId)
                store.select(selected.id)
              }}
            />
          </aside>
        </div>
      )}

      <Dialog
        open={showValidation}
        title="Validação do modelo"
        description={
          report.ok
            ? 'Pode publicar: nenhum erro encontrado.'
            : `${report.errors.length} erro(s) impedem a publicação.`
        }
        onClose={() => setShowValidation(false)}
        footer={<Button onClick={() => setShowValidation(false)}>Fechar</Button>}
      >
        <div className="max-h-80 overflow-auto rounded-md border">
          <ValidationPanel
            report={report}
            onSelectComponent={(componentId, tabId) => {
              if (tabId !== undefined) store.setActiveTab(tabId)
              store.select(componentId)
              setShowValidation(false)
            }}
          />
        </div>
      </Dialog>

      {/*
        O guia abre por cima do construtor (e não noutra tela) para o mestre não perder a
        seleção nem o histórico do Desfazer enquanto consulta.
      */}
      <Dialog
        open={showGuide}
        title="Guia de fórmulas"
        description="Como escrever fórmulas e ligar um campo ao outro."
        onClose={() => setShowGuide(false)}
        className="max-w-4xl"
      >
        <div className="-mx-5 max-h-[70vh] overflow-y-auto border-t px-5 pt-4">
          <FormulaGuide compact />
        </div>
      </Dialog>

      <Dialog
        open={deleteTarget !== null}
        title={`Excluir "${deleteTarget?.label ?? ''}"?`}
        description="O componente sai do modelo. Dá para desfazer com Ctrl+Z."
        onClose={() => setDeleteTarget(null)}
        footer={
          <>
            <Button variant="ghost" onClick={() => setDeleteTarget(null)}>
              Cancelar
            </Button>
            <Button variant="destructive" onClick={confirmDelete}>
              Excluir
            </Button>
          </>
        }
      >
        {usages.length > 0 && (
          <div className="border-destructive/40 bg-destructive/10 rounded-md border p-3 text-sm">
            <p className="mb-1 font-medium">
              A chave <code>{deleteTarget?.key}</code> é usada em {usages.length} fórmula(s):
            </p>
            <ul className="text-muted-foreground list-inside list-disc">
              {usages.slice(0, 6).map((usage, index) => (
                <li key={index}>{usage.slot.label}</li>
              ))}
            </ul>
            <p className="mt-2">Elas vão mostrar #ERRO até você corrigir.</p>
          </div>
        )}
      </Dialog>
    </div>
  )
}
