import { describe, expect, it } from 'vitest'
import {
  isAutoGeneratedKey,
  isReservedKey,
  isValidKeyFormat,
  keyFromLabel,
  slugifyKey,
  uniqueKey
} from './keys'

describe('slugifyKey', () => {
  it('tira acento e espaço, como manda a especificação', () => {
    expect(slugifyKey('Força')).toBe('forca')
    expect(slugifyKey('Pontos de Vida')).toBe('pontos_de_vida')
    expect(slugifyKey('Inteligência')).toBe('inteligencia')
    expect(slugifyKey('Ação / Reação')).toBe('acao_reacao')
  })

  it('não deixa a chave começar com número', () => {
    expect(slugifyKey('3 desejos')).toBe('campo_3_desejos')
  })

  it('devolve algo utilizável para rótulo sem letras', () => {
    expect(slugifyKey('???')).toBe('campo')
    expect(slugifyKey('')).toBe('campo')
  })

  it('corta chave gigante', () => {
    expect(slugifyKey('a'.repeat(80)).length).toBeLessThanOrEqual(40)
  })
})

describe('isValidKeyFormat', () => {
  it('aceita o que a linguagem de fórmulas entende', () => {
    expect(isValidKeyFormat('forca')).toBe(true)
    expect(isValidKeyFormat('_oculto')).toBe(true)
    expect(isValidKeyFormat('pontos_de_vida2')).toBe(true)
  })

  it('recusa o que quebraria a fórmula', () => {
    expect(isValidKeyFormat('')).toBe(false)
    expect(isValidKeyFormat('2dados')).toBe(false)
    expect(isValidKeyFormat('com espaço')).toBe(false)
    expect(isValidKeyFormat('tem-traco')).toBe(false)
    expect(isValidKeyFormat('ponto.ponto')).toBe(false)
  })
})

describe('isReservedKey', () => {
  it('protege as palavras da linguagem', () => {
    expect(isReservedKey('e')).toBe(true)
    expect(isReservedKey('ou')).toBe(true)
    expect(isReservedKey('nao')).toBe(true)
    expect(isReservedKey('piso')).toBe(true)
    expect(isReservedKey('soma')).toBe(true)
    expect(isReservedKey('valor')).toBe(true)
    expect(isReservedKey('SE')).toBe(true)
  })

  it('deixa passar chave comum', () => {
    expect(isReservedKey('forca')).toBe(false)
    expect(isReservedKey('vida')).toBe(false)
  })
})

describe('uniqueKey', () => {
  it('devolve a própria chave quando está livre', () => {
    expect(uniqueKey('forca', [])).toBe('forca')
  })

  it('numera quando já existe', () => {
    expect(uniqueKey('forca', ['forca'])).toBe('forca_2')
    expect(uniqueKey('forca', ['forca', 'forca_2'])).toBe('forca_3')
  })

  it('não devolve palavra reservada', () => {
    expect(uniqueKey('soma', [])).toBe('soma_2')
  })
})

describe('keyFromLabel', () => {
  it('junta slug e unicidade', () => {
    expect(keyFromLabel('Força', ['forca'])).toBe('forca_2')
    expect(keyFromLabel('Pontos de Vida', [])).toBe('pontos_de_vida')
  })
})

describe('isAutoGeneratedKey', () => {
  it('reconhece a chave que veio do rótulo', () => {
    expect(isAutoGeneratedKey('forca', 'Força')).toBe(true)
    expect(isAutoGeneratedKey('atributo', 'Atributo')).toBe(true)
  })

  it('reconhece a chave numerada por repetição', () => {
    expect(isAutoGeneratedKey('atributo_2', 'Atributo')).toBe(true)
    expect(isAutoGeneratedKey('atributo_13', 'Atributo')).toBe(true)
  })

  it('não reconhece chave que o mestre escreveu', () => {
    expect(isAutoGeneratedKey('forca_principal', 'Força')).toBe(false)
    expect(isAutoGeneratedKey('for', 'Força')).toBe(false)
    expect(isAutoGeneratedKey('atributo_x', 'Atributo')).toBe(false)
  })

  it('não se confunde com rótulo cheio de caractere especial', () => {
    expect(isAutoGeneratedKey('a_b', 'a.*b')).toBe(true)
    expect(() => isAutoGeneratedKey('x', '([')).not.toThrow()
  })
})
