import { FUNCTION_NAMES } from '../formula'

/**
 * Chaves dos componentes (seção 5.2): geradas do rótulo, únicas e editáveis.
 *
 * `Força` vira `forca` porque a chave entra nas fórmulas, e acento e espaço ali só
 * atrapalhariam quem escreve `=piso((forca - 10) / 2)`.
 */

/** Palavras que a linguagem de fórmulas usa e que não podem ser chave. */
export const RESERVED_KEYS: ReadonlySet<string> = new Set([
  'e',
  'ou',
  'nao',
  // `valor` é o nome do próprio valor dentro da fórmula do modificador de atributo.
  'valor',
  ...FUNCTION_NAMES
])

const MAX_KEY_LENGTH = 40

/** Formato aceito: começa com letra ou _, e segue com letras, números ou _. */
const VALID_KEY = /^[\p{L}_][\p{L}\p{N}_]*$/u

export function slugifyKey(label: string): string {
  const withoutAccents = label.normalize('NFD').replace(/[̀-ͯ]/g, '')

  const slug = withoutAccents
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, MAX_KEY_LENGTH)

  if (slug === '') return 'campo'
  // A linguagem não aceita identificador começando com número.
  return /^[0-9]/.test(slug) ? `campo_${slug}` : slug
}

export function isValidKeyFormat(key: string): boolean {
  return key.length > 0 && key.length <= MAX_KEY_LENGTH && VALID_KEY.test(key)
}

export function isReservedKey(key: string): boolean {
  return RESERVED_KEYS.has(key.toLowerCase())
}

/**
 * Primeira chave livre a partir de uma base: `forca`, `forca_2`, `forca_3`…
 * `taken` são as chaves já usadas (normalmente as do modelo inteiro).
 */
export function uniqueKey(base: string, taken: Iterable<string>): string {
  const used = new Set(taken)
  const seed = isValidKeyFormat(base) ? base : slugifyKey(base)

  if (!used.has(seed) && !isReservedKey(seed)) return seed

  for (let suffix = 2; suffix < 1000; suffix += 1) {
    const candidate = `${seed}_${suffix}`
    if (!used.has(candidate) && !isReservedKey(candidate)) return candidate
  }

  // Praticamente inalcançável; só para a função nunca devolver algo inválido.
  return `${seed}_${Date.now()}`
}

/** Chave sugerida para um rótulo novo, já livre no modelo. */
export function keyFromLabel(label: string, taken: Iterable<string>): string {
  return uniqueKey(slugifyKey(label), taken)
}

/**
 * A chave ainda é a que o app gerou a partir do rótulo?
 *
 * Serve para a chave continuar acompanhando o rótulo enquanto o mestre não a editar à mão
 * (5.2): ele cria um "Atributo", escreve "Força" e a chave vira `forca` sozinha. Depois de
 * editar a chave, ela para de ser mexida.
 */
export function isAutoGeneratedKey(key: string, label: string): boolean {
  const slug = slugifyKey(label)
  if (key === slug) return true
  // Chaves numeradas por causa de repetição (`atributo_2`) também contam como geradas.
  return new RegExp(`^${escapeForRegExp(slug)}_[0-9]+$`).test(key)
}

function escapeForRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}
